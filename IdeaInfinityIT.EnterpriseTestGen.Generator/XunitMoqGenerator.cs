        public string GenerateTestClass(
            ClassAnalysis classInfo, 
            List<BusinessRuleModel>? businessRules = null, 
            CustomScenarioFile? customScenarios = null,
            List<string>? selectedMethods = null)
        {
            var (code, _) = GenerateTestClassWithMetadata(classInfo, businessRules, customScenarios, selectedMethods);
            return code;
        }

        public (string Code, List<GeneratedTestCaseSummary> TestCases) GenerateTestClassWithMetadata(
            ClassAnalysis classInfo, 
            List<BusinessRuleModel>? businessRules = null, 
            CustomScenarioFile? customScenarios = null,
            List<string>? selectedMethods = null)
        {
            var sb = new StringBuilder();
            var testCases = new List<GeneratedTestCaseSummary>();

            bool isController = classInfo.IsWebController || classInfo.IsApiController || classInfo.ClassName.EndsWith("Controller");
            string sutVar = isController ? "_controller" : "_service";
            string roleLabel = classInfo.IsWebController ? "Web Client MVC Controller" : (classInfo.IsApiController ? "Server Web API Controller" : "Domain / Transaction Service");

            sb.AppendLine("// =========================================================================");
            sb.AppendLine("// AUTO-GENERATED BY EnterpriseTestGen Studio");
            sb.AppendLine($"// Target Class:       {classInfo.ClassName}");
            sb.AppendLine($"// Architecture Role:  {roleLabel}");
            sb.AppendLine($"// Target Namespace:   {classInfo.Namespace}");
            sb.AppendLine($"// Injected Mocks:     {classInfo.ConstructorDependencies.Count}");
            sb.AppendLine($"// Generated on:       {DateTime.Now:yyyy-MM-dd HH:mm:ss}");
            sb.AppendLine("// =========================================================================");
            sb.AppendLine();
            sb.AppendLine("using System;");
            sb.AppendLine("using System.Collections.Generic;");
            sb.AppendLine("using System.Linq;");
            sb.AppendLine("using System.Threading.Tasks;");
            sb.AppendLine("using Xunit;");
            sb.AppendLine("using Moq;");
            sb.AppendLine("using FluentAssertions;");
            if (isController)
            {
                sb.AppendLine("using Microsoft.AspNetCore.Mvc;");
            }
            sb.AppendLine($"using {classInfo.Namespace};");
            sb.AppendLine();

            sb.AppendLine($"namespace {classInfo.Namespace}.Tests");
            sb.AppendLine("{");
            sb.AppendLine($"    public class {classInfo.ClassName}Tests");
            sb.AppendLine("    {");

            // Declare Mock Fields
            foreach (var dep in classInfo.ConstructorDependencies)
            {
                var mockName = GetMockFieldName(dep.InterfaceName);
                sb.AppendLine($"        private readonly Mock<{dep.InterfaceName}> {mockName};");
            }
            sb.AppendLine($"        private readonly {classInfo.ClassName} {sutVar};");
            sb.AppendLine();

            // Constructor
            sb.AppendLine($"        public {classInfo.ClassName}Tests()");
            sb.AppendLine("        {");
            foreach (var dep in classInfo.ConstructorDependencies)
            {
                var mockName = GetMockFieldName(dep.InterfaceName);
                sb.AppendLine($"            {mockName} = new Mock<{dep.InterfaceName}>();");
            }

            sb.Append($"            {sutVar} = new {classInfo.ClassName}(");
            var ctorArgs = classInfo.ConstructorDependencies.Select(d => $"{GetMockFieldName(d.InterfaceName)}.Object");
            sb.Append(string.Join(", ", ctorArgs));
            sb.AppendLine(");");
            sb.AppendLine("        }");
            sb.AppendLine();

            // Methods
            foreach (var method in classInfo.Methods)
            {
                if (method.MethodName.StartsWith("get_") || method.MethodName.StartsWith("set_"))
                    continue;

                if (selectedMethods != null && selectedMethods.Count > 0 && !selectedMethods.Contains(method.MethodName))
                    continue;

                GenerateMethodTests(sb, classInfo, method, sutVar, businessRules, customScenarios, testCases);
            }

            sb.AppendLine("    }");
            sb.AppendLine("}");

            return (sb.ToString(), testCases);
        }

        private void GenerateMethodTests(
            StringBuilder sb, 
            ClassAnalysis classInfo, 
            MethodAnalysis method, 
            string sutVar,
            List<BusinessRuleModel>? businessRules, 
            CustomScenarioFile? customScenarios,
            List<GeneratedTestCaseSummary> testCases)
        {
            var isAsync = method.IsAsync || method.ReturnType.StartsWith("Task");
            var returnSignature = isAsync ? "async Task" : "void";
            var awaitPrefix = isAsync ? "await " : "";
            bool isController = classInfo.IsWebController || classInfo.IsApiController || classInfo.ClassName.EndsWith("Controller");

            // --- TEST 1: Default / Happy Path Scenario ---
            var happyTestName = isController 
                ? $"{method.MethodName}_WhenCalled_ReturnsValidActionResult" 
                : $"{method.MethodName}_WithValidInputs_ExecutesSuccessfully";

            testCases.Add(new GeneratedTestCaseSummary
            {
                TestName = happyTestName,
                TargetMethod = method.MethodName,
                Category = "HappyPath",
                Description = $"Verifies {method.MethodName} executes standard workflow without unhandled exceptions.",
                ExpectedAssertion = isController ? "Returns valid IActionResult / ActionResult" : "Executes without throwing exceptions"
            });

            sb.AppendLine($"        // ── {method.MethodName} ─────────────────────────────────────────");
            sb.AppendLine($"        [Fact]");
            sb.AppendLine($"        [Trait(\"Category\", \"HappyPath\")]");
            sb.AppendLine($"        public {returnSignature} {happyTestName}()");
            sb.AppendLine("        {");
            sb.AppendLine("            // Arrange");

            var callArgs = new List<string>();
            foreach (var p in method.Parameters)
            {
                var val = GetSampleValueForType(p.Type);
                sb.AppendLine($"            var {p.Name} = {val};");
                callArgs.Add(p.Name);
            }

            // Arrange Injected Mocks (Intelligent Mocking)
            if (method.InvokedDependencies.Any())
            {
                sb.AppendLine();
                sb.AppendLine("            // Configure Injected Mock Behaviors");
                foreach (var inv in method.InvokedDependencies)
                {
                    var mockName = GetMockFieldName(inv.InterfaceName);
                    var itArgs = GetItIsAnyArgs(inv.ArgumentCount, inv.ArgumentTypes);
                    if (inv.IsAsync)
                    {
                        bool isLikelyVoidTask = inv.MethodName.StartsWith("Save") || inv.MethodName.StartsWith("Delete") || 
                                                inv.MethodName.StartsWith("Update") || inv.MethodName.StartsWith("Send") || 
                                                inv.MethodName.StartsWith("Notify");
                        sb.AppendLine($"            {mockName}.Setup(x => x.{inv.MethodName}({itArgs}))");
                        if (isLikelyVoidTask)
                        {
                            sb.AppendLine($"                .Returns(Task.CompletedTask);");
                        }
                        else
                        {
                            sb.AppendLine($"                .ReturnsAsync(true);");
                        }
                    }
                    else
                    {
                        sb.AppendLine($"            {mockName}.Setup(x => x.{inv.MethodName}({itArgs}))");
                        sb.AppendLine($"                .Returns(true);");
                    }
                }
            }

            sb.AppendLine();
            sb.AppendLine("            // Act");
            if (isController)
            {
                sb.AppendLine($"            var result = {awaitPrefix}{sutVar}.{method.MethodName}({string.Join(", ", callArgs)});");
                sb.AppendLine();
                sb.AppendLine("            // Assert");
                sb.AppendLine("            result.Should().NotBeNull();");
                if (classInfo.IsApiController)
                {
                    sb.AppendLine("            // Assert Web API response is OkObjectResult or valid ActionResult");
                    sb.AppendLine("            result.Should().BeAssignableTo<IActionResult>();");
                }
                else
                {
                    sb.AppendLine("            // Assert Web MVC response is IActionResult (ViewResult or JsonResult)");
                    sb.AppendLine("            result.Should().BeAssignableTo<IActionResult>();");
                }
            }
            else
            {
                if (HasReturnValue(method))
                {
                    sb.AppendLine($"            var result = {awaitPrefix}{sutVar}.{method.MethodName}({string.Join(", ", callArgs)});");
                    sb.AppendLine();
                    AppendReturnAssertion(sb, method);
                }
                else
                {
                    if (isAsync)
                    {
                        sb.AppendLine($"            Func<Task> act = async () => await {sutVar}.{method.MethodName}({string.Join(", ", callArgs)});");
                        sb.AppendLine();
                        sb.AppendLine("            // Assert");
                        sb.AppendLine("            await act.Should().NotThrowAsync();");
                    }
                    else
                    {
                        sb.AppendLine($"            Action act = () => {sutVar}.{method.MethodName}({string.Join(", ", callArgs)});");
                        sb.AppendLine();
                        sb.AppendLine("            // Assert");
                        sb.AppendLine("            act.Should().NotThrow();");
                    }
                }
            }

            // Verify Mock Interactions
            if (method.InvokedDependencies.Any())
            {
                sb.AppendLine();
                sb.AppendLine("            // Assert Mock Interactions");
                foreach (var inv in method.InvokedDependencies)
                {
                    var mockName = GetMockFieldName(inv.InterfaceName);
                    var itArgs = GetItIsAnyArgs(inv.ArgumentCount, inv.ArgumentTypes);
                    sb.AppendLine($"            {mockName}.Verify(x => x.{inv.MethodName}({itArgs}), Times.AtLeastOnce);");
                }
            }
            sb.AppendLine("        }");
            sb.AppendLine();

            // --- TEST 2: Defensive Null Guard Validation ---
            var refParams = method.Parameters.Where(p => 
                p.Type == "string" || 
                p.Type.EndsWith("Entity") || 
                p.Type.EndsWith("Model") || 
                p.Type.EndsWith("Dto") || 
                !p.Type.All(char.IsLower)).ToList();

            if (refParams.Any())
            {
                var targetP = refParams.First();
                var nullTestName = $"{method.MethodName}_When_{targetP.Name}IsNull_HandlesDefensively";

                testCases.Add(new GeneratedTestCaseSummary
                {
                    TestName = nullTestName,
                    TargetMethod = method.MethodName,
                    Category = "NullValidation",
                    Description = $"Ensures {method.MethodName} does not crash when '{targetP.Name}' is passed as null.",
                    ExpectedAssertion = "Handles null gracefully or returns expected error code"
                });

                sb.AppendLine($"        [Fact]");
                sb.AppendLine($"        [Trait(\"Category\", \"NullValidation\")]");
                sb.AppendLine($"        public {returnSignature} {nullTestName}()");
                sb.AppendLine("        {");
                sb.AppendLine("            // Arrange - Null Guard Injection");
                var nullCallArgs = new List<string>();
                foreach (var p in method.Parameters)
                {
                    if (p.Name == targetP.Name)
                    {
                        sb.AppendLine($"            {p.Type} {p.Name} = null!;");
                    }
                    else
                    {
                        sb.AppendLine($"            var {p.Name} = {GetSampleValueForType(p.Type)};");
                    }
                    nullCallArgs.Add(p.Name);
                }

                sb.AppendLine();
                sb.AppendLine("            // Act & Assert");
                if (isAsync)
                {
                    sb.AppendLine($"            Func<Task> act = async () => await {sutVar}.{method.MethodName}({string.Join(", ", nullCallArgs)});");
                    sb.AppendLine("            await act.Should().NotThrowAsync<NullReferenceException>();");
                }
                else
                {
                    sb.AppendLine($"            Action act = () => {sutVar}.{method.MethodName}({string.Join(", ", nullCallArgs)});");
                    sb.AppendLine("            act.Should().NotThrow<NullReferenceException>();");
                }
                sb.AppendLine("        }");
                sb.AppendLine();
            }

            // --- TEST 3: Numerical / Boundary ID Check ---
            var idParam = method.Parameters.FirstOrDefault(p => 
                p.Type == "int" || p.Type == "long" || p.Name.IndexOf("id", StringComparison.OrdinalIgnoreCase) >= 0);

            if (idParam != null)
            {
                var boundaryTestName = $"{method.MethodName}_When_{idParam.Name}IsNegativeOrZero_HandlesGracefully";

                testCases.Add(new GeneratedTestCaseSummary
                {
                    TestName = boundaryTestName,
                    TargetMethod = method.MethodName,
                    Category = "Boundary",
                    Description = $"Verifies {method.MethodName} handles boundary key value: {idParam.Name} = -1.",
                    ExpectedAssertion = "Handles non-existent key defensively"
                });

                sb.AppendLine($"        [Fact]");
                sb.AppendLine($"        [Trait(\"Category\", \"Boundary\")]");
                sb.AppendLine($"        public {returnSignature} {boundaryTestName}()");
                sb.AppendLine("        {");
                sb.AppendLine("            // Arrange - Boundary Identifier: -1");
                var boundaryArgs = new List<string>();
                foreach (var p in method.Parameters)
                {
                    if (p.Name == idParam.Name)
                    {
                        sb.AppendLine($"            {p.Type} {p.Name} = -1;");
                    }
                    else
                    {
                        sb.AppendLine($"            var {p.Name} = {GetSampleValueForType(p.Type)};");
                    }
                    boundaryArgs.Add(p.Name);
                }

                sb.AppendLine();
                sb.AppendLine("            // Act");
                if (HasReturnValue(method))
                {
                    sb.AppendLine($"            var result = {awaitPrefix}{sutVar}.{method.MethodName}({string.Join(", ", boundaryArgs)});");
                    sb.AppendLine();
                    AppendReturnAssertion(sb, method);
                }
                else
                {
                    if (isAsync)
                    {
                        sb.AppendLine($"            Func<Task> act = async () => await {sutVar}.{method.MethodName}({string.Join(", ", boundaryArgs)});");
                        sb.AppendLine();
                        sb.AppendLine("            // Assert");
                        sb.AppendLine("            await act.Should().NotThrowAsync();");
                    }
                    else
                    {
                        sb.AppendLine($"            Action act = () => {sutVar}.{method.MethodName}({string.Join(", ", boundaryArgs)});");
                        sb.AppendLine();
                        sb.AppendLine("            // Assert");
                        sb.AppendLine("            act.Should().NotThrow();");
                    }
                }
                sb.AppendLine("        }");
                sb.AppendLine();
            }

            // --- TEST 4: User Custom Scenarios from YAML (if provided) ---
            if (customScenarios != null && 
                (string.Equals(customScenarios.TargetMethod, method.MethodName, StringComparison.OrdinalIgnoreCase) ||
                 string.IsNullOrEmpty(customScenarios.TargetMethod)))
            {
                foreach (var customCase in customScenarios.CustomTestCases)
                {
                    var customTestName = $"{method.MethodName}_{customCase.Name}";
                    testCases.Add(new GeneratedTestCaseSummary
                    {
                        TestName = customTestName,
                        TargetMethod = method.MethodName,
                        Category = "UserCustom",
                        Description = customCase.Description,
                        ExpectedAssertion = "Validates user custom Given/Expected contract"
                    });

                    sb.AppendLine($"        [Fact]");
                    sb.AppendLine($"        [Trait(\"Source\", \"User_Custom_Case\")]");
                    sb.AppendLine($"        [Trait(\"Description\", \"{customCase.Description.Replace("\"", "'")}\")]");
                    sb.AppendLine($"        public {returnSignature} {customTestName}()");
                    sb.AppendLine("        {");
                    sb.AppendLine($"            // User Custom Scenario: {customCase.Description}");
                    sb.AppendLine("            // Arrange");
                    foreach (var g in customCase.Given)
                    {
                        sb.AppendLine($"            // Given: {g.Key} = {g.Value}");
                    }
                    sb.AppendLine();
                    sb.AppendLine("            // Act");
                    if (HasReturnValue(method))
                    {
                        sb.AppendLine($"            var result = {awaitPrefix}{sutVar}.{method.MethodName}({string.Join(", ", method.Parameters.Select(p => GetSampleValueForType(p.Type)))});");
                        sb.AppendLine();
                        AppendReturnAssertion(sb, method);
                    }
                    else
                    {
                        if (isAsync)
                        {
                            sb.AppendLine($"            Func<Task> act = async () => await {sutVar}.{method.MethodName}({string.Join(", ", method.Parameters.Select(p => GetSampleValueForType(p.Type)))});");
                            sb.AppendLine();
                            sb.AppendLine("            // Assert");
                            sb.AppendLine("            await act.Should().NotThrowAsync();");
                        }
                        else
                        {
                            sb.AppendLine($"            Action act = () => {sutVar}.{method.MethodName}({string.Join(", ", method.Parameters.Select(p => GetSampleValueForType(p.Type)))});");
                            sb.AppendLine();
                            sb.AppendLine("            // Assert");
                            sb.AppendLine("            act.Should().NotThrow();");
                        }
                    }
                    sb.AppendLine("        }");
                    sb.AppendLine();
                }
            }

            // --- TEST 5: Business Rules from BRD Document (if provided) ---
            if (businessRules != null && businessRules.Any())
            {
                var matchedRule = businessRules.FirstOrDefault(r => 
                    r.Condition.IndexOf(method.MethodName, StringComparison.OrdinalIgnoreCase) >= 0 ||
                    r.ExpectedOutcome.IndexOf(method.MethodName, StringComparison.OrdinalIgnoreCase) >= 0)
                    ?? businessRules.FirstOrDefault();

                if (matchedRule != null)
                {
                    var brdTestName = $"{method.MethodName}_Enforces_{matchedRule.RuleId.Replace("-", "_")}";
                    testCases.Add(new GeneratedTestCaseSummary
                    {
                        TestName = brdTestName,
                        TargetMethod = method.MethodName,
                        Category = "BRD",
                        Description = matchedRule.Condition,
                        ExpectedAssertion = matchedRule.ExpectedOutcome
                    });

                    sb.AppendLine($"        [Fact]");
                    sb.AppendLine($"        [Trait(\"Source\", \"BRD_Document\")]");
                    sb.AppendLine($"        [Trait(\"RuleId\", \"{matchedRule.RuleId}\")]");
                    sb.AppendLine($"        public {returnSignature} {brdTestName}()");
                    sb.AppendLine("        {");
                    sb.AppendLine($"            // BRD Condition: {matchedRule.Condition.Replace("\"", "'")}");
                    sb.AppendLine($"            // Expected:      {matchedRule.ExpectedOutcome.Replace("\"", "'")}");
                    sb.AppendLine("            // Act");
                    if (HasReturnValue(method))
                    {
                        sb.AppendLine($"            var result = {awaitPrefix}{sutVar}.{method.MethodName}({string.Join(", ", method.Parameters.Select(p => GetSampleValueForType(p.Type)))});");
                        sb.AppendLine("            result.Should().NotBeNull();");
                    }
                    else
                    {
                        if (isAsync)
                        {
                            sb.AppendLine($"            Func<Task> act = async () => await {sutVar}.{method.MethodName}({string.Join(", ", method.Parameters.Select(p => GetSampleValueForType(p.Type)))});");
                            sb.AppendLine("            await act.Should().NotThrowAsync();");
                        }
                        else
                        {
                            sb.AppendLine($"            Action act = () => {sutVar}.{method.MethodName}({string.Join(", ", method.Parameters.Select(p => GetSampleValueForType(p.Type)))});");
                            sb.AppendLine("            act.Should().NotThrow();");
                        }
                    }
                    sb.AppendLine("        }");
                    sb.AppendLine();
                }
            }
        }

        private static bool IsVoidReturn(MethodAnalysis method)
        {
            var rt = method.ReturnType?.Trim() ?? "";
            return rt == "void";
        }

        private static bool IsTaskWithoutResult(MethodAnalysis method)
        {
            var rt = method.ReturnType?.Trim() ?? "";
            return rt == "Task" || rt == "ValueTask" || rt == "System.Threading.Tasks.Task" || rt == "System.Threading.Tasks.ValueTask";
        }

        private static bool HasReturnValue(MethodAnalysis method)
        {
            return !IsVoidReturn(method) && !IsTaskWithoutResult(method);
        }

        private static void AppendReturnAssertion(StringBuilder sb, MethodAnalysis method)
        {
            sb.AppendLine("            // Assert");
            sb.AppendLine("            result.Should().NotBeNull();");
            if (method.ReturnType == "bool" || method.ReturnType == "Task<bool>" || method.ReturnType == "ValueTask<bool>")
            {
                sb.AppendLine("            result.Should().BeTrue();");
            }
            else
            {
                var unwrappedType = method.ReturnType?.Trim() ?? "object";
                if (unwrappedType.StartsWith("Task<") && unwrappedType.EndsWith(">"))
                    unwrappedType = unwrappedType.Substring(5, unwrappedType.Length - 6);
                else if (unwrappedType.StartsWith("ValueTask<") && unwrappedType.EndsWith(">"))
                    unwrappedType = unwrappedType.Substring(10, unwrappedType.Length - 11);

                sb.AppendLine($"            result.Should().BeAssignableTo<{unwrappedType}>();");
            }
        }

        private string GetMockFieldName(string interfaceName)
        {
            var clean = interfaceName.TrimStart('I');
            clean = clean.Replace("<", "_").Replace(">", "").Replace(",", "_").Replace(" ", "").TrimEnd('_');
            return $"_mock{clean}";
        }

        private string GetItIsAnyArgs(int argumentCount, List<string>? argumentTypes = null)
        {
            if (argumentCount <= 0) return "";
            var list = new List<string>();
            for (int i = 0; i < argumentCount; i++)
            {
                string type = (argumentTypes != null && i < argumentTypes.Count && !string.IsNullOrWhiteSpace(argumentTypes[i]))
                    ? argumentTypes[i]
                    : "object";
                list.Add($"It.IsAny<{type}>()");
            }
            return string.Join(", ", list);
        }

        public List<TestSpecification> PlanTestSpecifications(
            ClassAnalysis classInfo,
            List<BusinessRuleModel>? businessRules = null,
            CustomScenarioFile? customScenarios = null,
            List<string>? selectedMethods = null)
        {
            var specs = new List<TestSpecification>();
            int specIndex = 1;
            bool isController = classInfo.IsWebController || classInfo.IsApiController || classInfo.ClassName.EndsWith("Controller");

            foreach (var method in classInfo.Methods)
            {
                if (method.MethodName.StartsWith("get_") || method.MethodName.StartsWith("set_"))
                    continue;

                if (selectedMethods != null && selectedMethods.Count > 0 && !selectedMethods.Contains(method.MethodName))
                    continue;

                // 1. Happy Path Spec
                var happySpec = new TestSpecification
                {
                    ScenarioId = $"SPEC-{specIndex++:D3}",
                    TargetClass = classInfo.ClassName,
                    TargetMethod = method.MethodName,
                    TestName = isController ? $"{method.MethodName}_WhenCalled_ReturnsValidActionResult" : $"{method.MethodName}_WithValidInputs_ExecutesSuccessfully",
                    Category = "HappyPath",
                    Priority = "High",
                    Description = $"Executes {method.MethodName} with standard valid contract and verifies successful response.",
                    ExpectedOutcome = isController ? "Returns valid IActionResult with successful status code" : "Executes without unhandled exceptions",
                    ConfidenceScore = 0.95
                };
                foreach (var p in method.Parameters)
                {
                    happySpec.Inputs[p.Name] = GetSampleValueForType(p.Type);
                }
                foreach (var inv in method.InvokedDependencies)
                {
                    happySpec.MockSetups.Add(new MockSetupDefinition
                    {
                        MockFieldName = GetMockFieldName(inv.InterfaceName),
                        InterfaceName = inv.InterfaceName,
                        MethodName = inv.MethodName,
                        IsAsync = inv.IsAsync,
                        ReturnExpression = inv.IsAsync ? "ReturnsAsync(true)" : "Returns(true)"
                    });
                }
                specs.Add(happySpec);

                // 2. Null Validation Spec
                var refParam = method.Parameters.FirstOrDefault(p => p.Type == "string" || !p.Type.All(char.IsLower));
                if (refParam != null)
                {
                    var nullSpec = new TestSpecification
                    {
                        ScenarioId = $"SPEC-{specIndex++:D3}",
                        TargetClass = classInfo.ClassName,
                        TargetMethod = method.MethodName,
                        TestName = $"{method.MethodName}_When_{refParam.Name}IsNull_HandlesDefensively",
                        Category = "NullValidation",
                        Priority = "Medium",
                        Description = $"Verifies defensive guard handling when parameter '{refParam.Name}' is null.",
                        ExpectedOutcome = "Handles null without unhandled NullReferenceException",
                        ConfidenceScore = 0.90
                    };
                    nullSpec.Inputs[refParam.Name] = "null";
                    specs.Add(nullSpec);
                }

                // 3. Boundary Spec
                var idParam = method.Parameters.FirstOrDefault(p => p.Type == "int" || p.Type == "long" || p.Name.IndexOf("id", StringComparison.OrdinalIgnoreCase) >= 0);
                if (idParam != null)
                {
                    var boundarySpec = new TestSpecification
                    {
                        ScenarioId = $"SPEC-{specIndex++:D3}",
                        TargetClass = classInfo.ClassName,
                        TargetMethod = method.MethodName,
                        TestName = $"{method.MethodName}_When_{idParam.Name}IsNegativeOrZero_HandlesGracefully",
                        Category = "Boundary",
                        Priority = "Medium",
                        Description = $"Verifies boundary handling when key parameter '{idParam.Name}' is negative or zero.",
                        ExpectedOutcome = "Handles non-existent or boundary key gracefully",
                        ConfidenceScore = 0.85
                    };
                    boundarySpec.Inputs[idParam.Name] = "-1";
                    specs.Add(boundarySpec);
                }
            }

            return specs;
        }

        private string GetSampleValueForType(string type)
        {
            if (string.IsNullOrWhiteSpace(type)) return "default!";
            type = type.TrimEnd('?').Trim();

            var lower = type.ToLowerInvariant();
            if (lower == "int" || lower == "int32") return "1";
            if (lower == "long" || lower == "int64") return "1L";
            if (lower == "short" || lower == "int16") return "1";
            if (lower == "byte") return "(byte)1";
            if (lower == "decimal") return "100.00m";
            if (lower == "double") return "1.0";
            if (lower == "float" || lower == "single") return "1.0f";
            if (lower == "string") return "\"TestSample\"";
            if (lower == "char") return "'A'";
            if (lower == "bool" || lower == "boolean") return "true";
            if (lower == "datetime") return "DateTime.Now";
            if (lower == "datetimeoffset") return "DateTimeOffset.Now";
            if (lower == "guid") return "Guid.NewGuid()";
            if (lower == "cancellationtoken") return "CancellationToken.None";
            if (lower.StartsWith("ienumerable<") || lower.StartsWith("ilist<") || lower.StartsWith("list<"))
            {
                var inner = type.Substring(type.IndexOf('<') + 1).TrimEnd('>');
                return $"new List<{inner}>()";
            }
            if (lower.StartsWith("idictionary<") || lower.StartsWith("dictionary<"))
            {
                var inner = type.Substring(type.IndexOf('<') + 1).TrimEnd('>');
                return $"new Dictionary<{inner}>()";
            }
            if (lower.EndsWith("[]"))
            {
                var elemType = type.Substring(0, type.Length - 2);
                return $"Array.Empty<{elemType}>()";
            }
            if (type.StartsWith("I") && type.Length > 1 && char.IsUpper(type[1]))
            {
                return $"Mock.Of<{type}>()";
            }

            return $"new {type}()";
        }

        public string AugmentExistingTestClass(
            string existingTestFilePath, 
            ClassAnalysis classInfo, 
            List<TestCaseReviewItem> newReviewCases)
        {
            if (!System.IO.File.Exists(existingTestFilePath))
            {
                var (newCode, _) = GenerateTestClassWithMetadata(classInfo);
                return newCode;
            }

            var existingCode = System.IO.File.ReadAllText(existingTestFilePath);
            var approvedNewCases = newReviewCases
                .Where(c => c.IsApproved && !c.IsExisting && 
                            (string.IsNullOrEmpty(c.TargetClass) || string.Equals(c.TargetClass, classInfo.ClassName, StringComparison.OrdinalIgnoreCase)))
                .ToList();

            if (!approvedNewCases.Any())
                return existingCode; // Nothing new to add

            var sbNewTests = new StringBuilder();
            sbNewTests.AppendLine();
            sbNewTests.AppendLine("        // =========================================================================");
            sbNewTests.AppendLine($"        // ─── AUGMENTED / UPDATED BY EnterpriseTestGen Studio ({DateTime.Now:yyyy-MM-dd HH:mm:ss}) ───");
            sbNewTests.AppendLine($"        // Added {approvedNewCases.Count} missing edge-case & branch test scenarios");
            sbNewTests.AppendLine("        // =========================================================================");

            bool isController = classInfo.IsWebController || classInfo.IsApiController || classInfo.ClassName.EndsWith("Controller");
            string sutVar = isController ? "_controller" : "_service";

            foreach (var reviewCase in approvedNewCases)
            {
                var method = classInfo.Methods.FirstOrDefault(m => string.Equals(m.MethodName, reviewCase.TargetMethod, StringComparison.OrdinalIgnoreCase));
                var isAsync = method != null && (method.IsAsync || method.ReturnType.StartsWith("Task"));
                var returnSignature = isAsync ? "async Task" : "void";
                var awaitPrefix = isAsync ? "await " : "";

                sbNewTests.AppendLine();
                sbNewTests.AppendLine($"        [Fact]");
                sbNewTests.AppendLine($"        [Trait(\"Category\", \"{reviewCase.Category}\")]");
                sbNewTests.AppendLine($"        [Trait(\"Source\", \"AugmentedUpdate\")]");
                sbNewTests.AppendLine($"        public {returnSignature} {reviewCase.TestName}()");
                sbNewTests.AppendLine("        {");
                sbNewTests.AppendLine($"            // Scenario: {reviewCase.Category} - {reviewCase.ExpectedResult}");
                sbNewTests.AppendLine("            // Arrange");

                var callArgs = new List<string>();
                if (method != null)
                {
                    foreach (var p in method.Parameters)
                    {
                        if (reviewCase.Category == "NullValidation" && (p.Type == "string" || !p.Type.All(char.IsLower)))
                        {
                            sbNewTests.AppendLine($"            {p.Type} {p.Name} = null!;");
                        }
                        else
                        {
                            var val = GetSampleValueForType(p.Type);
                            sbNewTests.AppendLine($"            var {p.Name} = {val};");
                        }
                        callArgs.Add(p.Name);
                    }
                }

                sbNewTests.AppendLine();
                sbNewTests.AppendLine("            // Act");
                if (isController)
                {
                    sbNewTests.AppendLine($"            var result = {awaitPrefix}{sutVar}.{reviewCase.TargetMethod}({string.Join(", ", callArgs)});");
                    sbNewTests.AppendLine();
                    sbNewTests.AppendLine("            // Assert");
                    sbNewTests.AppendLine("            result.Should().NotBeNull();");
                    sbNewTests.AppendLine("            result.Should().BeAssignableTo<IActionResult>();");
                }
                else
                {
                    if (method != null && HasReturnValue(method))
                    {
                        sbNewTests.AppendLine($"            var result = {awaitPrefix}{sutVar}.{reviewCase.TargetMethod}({string.Join(", ", callArgs)});");
                        sbNewTests.AppendLine();
                        AppendReturnAssertion(sbNewTests, method);
                    }
                    else
                    {
                        if (isAsync)
                        {
                            sbNewTests.AppendLine($"            Func<Task> act = async () => await {sutVar}.{reviewCase.TargetMethod}({string.Join(", ", callArgs)});");
                            sbNewTests.AppendLine();
                            sbNewTests.AppendLine("            // Assert");
                            sbNewTests.AppendLine("            await act.Should().NotThrowAsync();");
                        }
                        else
                        {
                            sbNewTests.AppendLine($"            Action act = () => {sutVar}.{reviewCase.TargetMethod}({string.Join(", ", callArgs)});");
                            sbNewTests.AppendLine();
                            sbNewTests.AppendLine("            // Assert");
                            sbNewTests.AppendLine("            act.Should().NotThrow();");
                        }
                    }
                }

                sbNewTests.AppendLine("        }");
            }

            // Find the last closing brace of the class
            // In C# files with namespace { class { ... } }, the last two closing braces are class and namespace
            int lastCloseIndex = existingCode.LastIndexOf('}');
            if (lastCloseIndex > 0)
            {
                int secondLastCloseIndex = existingCode.LastIndexOf('}', lastCloseIndex - 1);
                if (secondLastCloseIndex > 0)
                {
                    return existingCode.Insert(secondLastCloseIndex, sbNewTests.ToString() + Environment.NewLine + "    ");
                }
                return existingCode.Insert(lastCloseIndex, sbNewTests.ToString() + Environment.NewLine);
            }

            return existingCode + sbNewTests.ToString();
        }
    }
